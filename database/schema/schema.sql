CREATE TABLE VENDA (
	COD_VENDA INT PRIMARY KEY AUTO_INCREMENT,
    COD_PAG INT NOT NULL,
    COD_PED INT, -- se permitirmos venda parcial de pedido, pode continuar assim, se não, UNIQUE
    COD_PROMO INT, -- se for possível adicionar mais de uma promoção na venda, terá que ser criado uma tabela associativa N:N
    DATA_VENDA DATE NOT NULL,
    VALOR_VENDA NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_venda_pag FOREIGN KEY (COD_PAG) REFERENCES FORMA_PAGAMENTO (COD_PAG),
    CONSTRAINT fk_venda_ped FOREIGN KEY (COD_PED) REFERENCES PEDIDO (COD_PED),
    CONSTRAINT fk_venda_pro FOREIGN KEY (COD_PROMO) REFERENCES PROMOCAO (COD_PROMO)
);

CREATE TABLE ITEM_PEDIDO (
	COD_PED INT NOT NULL, -- um determinado produto só pode apareceer uma vez dentro de um pedido
    COD_PROD INT NOT NULL, -- se o cliente for adicionar mais dele, só aumenta a quantidade ao invés de ccriar um novo registro
    QTD_PROD NUMERIC(5, 2) NOT NULL,
    VALOR_UNI NUMERIC(8, 2) NOT NULL,
    CONSTRAINT fk_item_ped FOREIGN KEY (COD_PED) REFERENCES PEDIDO (COD_PED),
    CONSTRAINT fk_item_prod FOREIGN KEY (COD_PROD) REFERENCES PRODUTO (COD_PROD),
    CONSTRAINT pk_item_prod_ped PRIMARY KEY (COD_PED, COD_PROD)
);

CREATE TABLE ITEM_PEDIDO_LOTE (
    COD_PED INT NOT NULL,
    COD_PROD INT NOT NULL,
    COD_LOTE INT NOT NULL,
    QTD_LOTE NUMERIC(10, 2) NOT NULL,
    CONSTRAINT pk_item_pedido_lote
        PRIMARY KEY (COD_PED, COD_PROD, COD_LOTE),
    CONSTRAINT fk_ipl_item
        FOREIGN KEY (COD_PED, COD_PROD)
        REFERENCES ITEM_PEDIDO (COD_PED, COD_PROD),
    CONSTRAINT fk_ipl_lote
        FOREIGN KEY (COD_LOTE)
        REFERENCES LOTE (COD_LOTE),
	CONSTRAINT fk_ipl_lote
		FOREIGN KEY (COD_LOTE, COD_PROD)
		REFERENCES LOTE (COD_LOTE, COD_PROD),
    CHECK (QTD_LOTE > 0)
);

