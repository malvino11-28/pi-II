CREATE TABLE ENDERECO (
	COD_END INT PRIMARY KEY AUTO_INCREMENT, -- pensando que um cliente/fornecedor pode ter mais de um endereço, precisa de um identificador unico para diferenciar
	COD_CLI INT,
    COD_FOR INT, -- esse ou o outro vai estar com o id
    RUA_END VARCHAR(255) NOT NULL,
    NUM_END VARCHAR (25),
    BAIRRO_END VARCHAR(255) NOT NULL,
    CIDADE_END VARCHAR (255) NOT NULL,
    ESTADO_END VARCHAR (2) NOT NULL,
    CEP_END VARCHAR(8) NOT NULL,
    CONSTRAINT fk_end_cli FOREIGN KEY (COD_CLI) REFERENCES CLIENTE (COD_CLI),
    CONSTRAINT fk_end_for FOREIGN KEY (COD_FOR) REFERENCES FORNECEDOR (COD_FOR),
    CHECK ((COD_CLI IS NOT NULL AND COD_FOR IS NULL) OR (COD_FOR IS NOT NULL AND COD_CLI IS NULL)) -- cliente ou fornecedor
);

CREATE TABLE CATEGORIA (
	COD_CAT INT PRIMARY KEY AUTO_INCREMENT,
    NOME_CAT VARCHAR (50) NOT NULL UNIQUE
);

CREATE TABLE MARCA (
	COD_MAR INT PRIMARY KEY AUTO_INCREMENT,
    NOME_MAR VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE PRODUTO (
	COD_PROD INT PRIMARY KEY AUTO_INCREMENT,
    COD_MAR INT NOT NULL,
    COD_CAT INT NOT NULL,
	NOME_PROD VARCHAR(100) NOT NULL,
    DESC_RED_PROD VARCHAR(255) NOT NULL, -- descrição reduzida (presente no site)
    DESC_PROD TEXT NOT NULL,
    UNI_MEDIDA_PROD ENUM('KG', 'G', 'UN', 'L', 'ML') NOT NULL,
    VALOR_UNI_PROD NUMERIC(6, 2) NOT NULL,
    CONSTRAINT fk_prod_mar FOREIGN KEY (COD_MAR) REFERENCES MARCA (COD_MAR),
    CONSTRAINT fk_prod_cat FOREIGN KEY (COD_CAT) REFERENCES CATEGORIA (COD_CAT),
    CHECK (VALOR_UNI_PROD >= 0),
    CHECK (EST_PROD >= 0)
);

CREATE TABLE PROMOCAO (
	COD_PROMO INT PRIMARY KEY AUTO_INCREMENT,
    NOME_PROMO VARCHAR(100) NOT NULL,
    TIPO_PROMO ENUM('Manual', 'Vencimento') DEFAULT 'Manual' NOT NULL,
    DESCONT_MON_PROMO NUMERIC(8, 2),
    DESCONT_PER_PROMO NUMERIC(5, 2),
    DATA_INIC_PROMO DATE NOT NULL,
    DATA_FIM_PROMO DATE NOT NULL,
    CHECK (DATA_FIM_PROMO >= DATA_INIC_PROMO),
    CHECK (DESCONT_MON_PROMO IS NULL OR DESCONT_MON_PROMO > 0),
    CHECK (DESCONT_PER_PROMO IS NULL OR (DESCONT_PER_PROMO > 0 AND DESCONT_PER_PROMO <= 100)),
	CHECK ((DESCONT_MON_PROMO IS NOT NULL AND DESCONT_PER_PROMO IS NULL) OR (DESCONT_PER_PROMO IS NOT NULL AND DESCONT_MON_PROMO IS NULL))
);


